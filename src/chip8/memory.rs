const FONTSET: [[u8; 5]; 16] = [
    [0xF0, 0x90, 0x90, 0x90, 0xF0],
    [0x20, 0x60, 0x20, 0x20, 0x70],
    [0xF0, 0x10, 0xF0, 0x80, 0xF0],
    [0xF0, 0x10, 0xF0, 0x10, 0xF0],
    [0x90, 0x90, 0xF0, 0x10, 0x10],
    [0xF0, 0x80, 0xF0, 0x10, 0xF0],
    [0xF0, 0x80, 0xF0, 0x90, 0xF0],
    [0xF0, 0x10, 0x20, 0x40, 0x40],
    [0xF0, 0x90, 0xF0, 0x90, 0xF0],
    [0xF0, 0x90, 0xF0, 0x10, 0xF0],
    [0xF0, 0x90, 0xF0, 0x90, 0x90],
    [0xE0, 0x90, 0xE0, 0x90, 0xE0],
    [0xF0, 0x80, 0x80, 0x80, 0xF0],
    [0xE0, 0x90, 0x90, 0x90, 0xE0],
    [0xF0, 0x80, 0xF0, 0x80, 0xF0],
    [0xF0, 0x80, 0xF0, 0x80, 0x80],
];


pub struct Memory {
    memory: [u8; 0x1000],
}

impl Memory {
    pub fn new() -> Self {
        let mut memory = Self { memory: [0; 0x1000] };
        for (idx, byte) in FONTSET.iter().enumerate() {
            memory.write_bytes(idx * 5, byte);
        }
        memory
    }
    pub fn read(&self, ptr: usize) -> u8 {
        self.memory[ptr]
    }
    pub fn write(&mut self, ptr: usize, value: u8) {
        self.memory[ptr] = value;
    }
    pub fn read_bytes(&mut self, ptr: usize, len: usize) -> &[u8] {
        &self.memory[ptr..ptr + len]
    }
    pub fn write_bytes(&mut self, ptr: usize, values: &[u8]) {
        self.memory[ptr..ptr + values.len()].copy_from_slice(values);
    }
    pub fn read_word(&self, ptr: usize) -> u16 {
        (self.memory[ptr] as u16) << 8 | (self.memory[ptr + 1] as u16)
    }
    pub fn load_memory(&mut self, data: &[u8]) {
        self.write_bytes(0x200, data);
    }
}


